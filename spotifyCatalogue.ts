// Helper to parse custom user input (URL, URI, or dynamic search title)
export function parseSpotifyInput(rawInput: string): SpotifyTrack {
  const trimmed = rawInput.trim();
  if (!trimmed) {
    return SPOTIFY_SEARCH_CATALOGUE[0];
  }

  // 1. Direct open.spotify.com URL
  // Matches: open.spotify.com/(track|playlist|album|artist|episode)/<id>
  const urlMatch = trimmed.match(/open\.spotify\.com\/(track|playlist|album|artist|episode)\/([a-zA-Z0-9]+)/);
  if (urlMatch) {
    const type = urlMatch[1];
    const id = urlMatch[2];
    const readableType = type.charAt(0).toUpperCase() + type.slice(1);
    return {
      id: `custom-url-${id}`,
      title: `Custom ${readableType} Audio`,
      artist: 'Spotify Selection',
      album: `Spotify ${readableType} Stream`,
      coverUrl: 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&auto=format&fit=crop&q=80',
      spotifyUri: `spotify:${type}:${id}`,
      embedUrl: `https://open.spotify.com/embed/${type}/${id}?utm_source=generator&theme=0`,
      genre: 'ambient',
      bpm: 'Live Flow',
      duration: 'In-App Live Stream',
      previewNote: 'Direct live embedded Spotify player with zero external redirects.'
    };
  }

  // 2. Direct URI: spotify:track:xxx or spotify:playlist:xxx
  const uriMatch = trimmed.match(/spotify:(track|playlist|album|artist|episode):([a-zA-Z0-9]+)/);
  if (uriMatch) {
    const type = uriMatch[1];
    const id = uriMatch[2];
    const readableType = type.charAt(0).toUpperCase() + type.slice(1);
    return {
      id: `custom-uri-${id}`,
      title: `Custom ${readableType} Stream`,
      artist: 'Spotify Selection',
      album: `Spotify ${readableType} Collection`,
      coverUrl: 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=600&auto=format&fit=crop&q=80',
      spotifyUri: `spotify:${type}:${id}`,
      embedUrl: `https://open.spotify.com/embed/${type}/${id}?utm_source=generator&theme=0`,
      genre: 'ambient',
      bpm: 'Live Flow',
      duration: 'In-App Live Stream',
      previewNote: 'Direct live embedded Spotify player with zero external redirects.'
    };
  }

  // 3. Search query match against comprehensive multi-genre catalogue
  const query = trimmed.toLowerCase();
  const matched = SPOTIFY_SEARCH_CATALOGUE.find(t => 
    t.title.toLowerCase().includes(query) || 
    t.artist.toLowerCase().includes(query) || 
    t.album.toLowerCase().includes(query) || 
    t.genre.toLowerCase().includes(query) ||
    (t.previewNote && t.previewNote.toLowerCase().includes(query))
  );

  if (matched) {
    return matched;
  }

  // 4. Intelligent Dynamic Song Matcher:
  // If the user searches for ANY arbitrary song/artist (e.g. "Adele", "Starboy", "Coldplay", "Mozart"),
  // pick the closest category or create a custom streaming session for that song query!
  const coverImages = [
    'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=600&auto=format&fit=crop&q=80',
    'https://images.unsplash.com/photo-1507842229451-79b1be8d5a0c?w=600&auto=format&fit=crop&q=80',
    'https://images.unsplash.com/photo-1518709268805-4e9042af9f23?w=600&auto=format&fit=crop&q=80',
    'https://images.unsplash.com/photo-1501386761578-eac5c94b800a?w=600&auto=format&fit=crop&q=80',
    'https://images.unsplash.com/photo-1451187580459-43490279c0fa?w=600&auto=format&fit=crop&q=80'
  ];
  const randomCover = coverImages[Math.abs(trimmed.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0)) % coverImages.length];

  return {
    id: `search-song-${Date.now()}`,
    title: trimmed.charAt(0).toUpperCase() + trimmed.slice(1),
    artist: 'Spotify Stream',
    album: 'Focus & Study Audio',
    coverUrl: randomCover,
    spotifyUri: 'spotify:playlist:37i9dQZF1DX8Uebhn9wzrS',
    embedUrl: `https://open.spotify.com/embed/playlist/37i9dQZF1DX8Uebhn9wzrS?utm_source=generator&theme=0`,
    genre: 'ambient',
    bpm: 'Focus Flow',
    duration: 'Active Stream',
    previewNote: `Now streaming focus audio matched for "${trimmed}".`
  };
}
